import { describe, it, expect } from 'vitest';
import { SmartDiff } from '@devdigest/shared';
import {
  buildSmartDiff,
  classifyFile,
  normalizePath,
  selectFindings,
  sortGroup,
} from '../src/modules/smart-diff/domain.js';
import type { ChangedFile, FindingRef, ReviewFindingsRead } from '../src/modules/smart-diff/ports.js';

const patch = (...added: string[]) => ['@@ -1,1 +1,2 @@', ...added.map((l) => `+${l}`)].join('\n');
const cls = (path: string, p: string | null = null) => classifyFile({ path, patch: p });

describe('normalizePath', () => {
  it('strips ./ and leading slash, unifies separators', () => {
    expect(normalizePath('./src/a.ts')).toBe('src/a.ts');
    expect(normalizePath('/src/a.ts')).toBe('src/a.ts');
    expect(normalizePath('src\\a.ts')).toBe('src/a.ts');
  });
});

describe('classifyFile', () => {
  it.each([
    'pnpm-lock.yaml', 'package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'bun.lock', 'bun.lockb',
    'Cargo.lock', 'go.sum', 'poetry.lock', 'uv.lock', 'Pipfile.lock', 'Gemfile.lock', 'composer.lock',
    'flake.lock', 'deno.lock', 'client/PNPM-LOCK.yaml',
  ])('lock %s -> boilerplate', (p) => expect(cls(p)).toBe('boilerplate'));

  it.each([
    'node_modules/x/index.js', 'server/src/vendor/shared/a.ts', 'dist/a.js', 'build/a.js', '.next/a.js',
    'coverage/lcov.info', 'a/b.min.js', 'a/b.min.css', 'a/b.js.map', 'a/types.d.ts', 'a/__snapshots__/x.ts',
    'a/x.snap', 'a/x.generated.ts', 'a/x_pb.ts', 'a/x.pb.go', 'server/src/db/migrations/meta/_journal.json',
    'server/src/db/migrations/0014_x.sql', 'prisma/migrations/1/migration.sql',
  ])('generated path %s -> boilerplate', (p) => expect(cls(p)).toBe('boilerplate'));

  it('@generated header in patch -> boilerplate', () => {
    expect(cls('src/a.ts', patch('// @generated by tool', 'x'))).toBe('boilerplate');
    expect(cls('src/a.ts', patch('// DO NOT EDIT'))).toBe('boilerplate');
  });
  it('marker beyond the first 5 add/ctx lines is ignored', () => {
    expect(cls('src/a.ts', patch('a', 'b', 'c', 'd', 'e', '// DO NOT EDIT'))).toBe('core');
  });
  it('removed lines and hunk headers are skipped by the content rule', () => {
    const p = ['@@ -1,2 +1,2 @@', '-// @generated', '+real', ' ctx'].join('\n');
    expect(cls('src/a.ts', p)).toBe('core');
  });

  it.each([
    'README.md', 'a/b.mdx', 'a/b.rst', 'docs/guide.txt', 'docs/a/b.png', 'LICENSE', 'LICENSE.md', 'CHANGELOG.md',
    'CHANGELOG',
  ])('docs %s', (p) => expect(cls(p)).toBe('docs'));
  it('.txt outside docs/ is core', () => expect(cls('src/notes.txt')).toBe('core'));

  it.each([
    'src/a.test.ts', 'src/a.spec.tsx', 'src/a.it.test.ts', 'src/__tests__/a.ts', 'src/__mocks__/a.ts',
    'server/test/a.ts', 'tests/a.py', 'e2e/specs/a.ts', 'src/fixtures/a.json', 'e2e/specs/05.flow.json',
    'a/b.flow.json',
  ])('tests %s', (p) => expect(cls(p)).toBe('tests'));

  it.each([
    'package.json', 'client/tsconfig.json', 'tsconfig.base.json', '.eslintrc.json', 'eslint.config.mjs',
    '.prettierrc', 'biome.json', 'vite.config.ts', 'vitest.config.ts', 'next.config.mjs', 'drizzle.config.ts',
    'tailwind.config.ts', 'postcss.config.js', 'Dockerfile', 'Dockerfile.dev', 'docker-compose.yml',
    '.github/workflows/ci.yml', '.gitlab-ci.yml', '.env.example', '.gitattributes', '.gitignore', '.editorconfig',
  ])('wiring %s', (p) => expect(cls(p)).toBe('wiring'));

  it('barrel with only re-exports and comments -> wiring', () => {
    const p = patch("export * from './a.js';", "export { b } from './b.js';", '// note', '/* c */', ' * d');
    expect(cls('src/index.ts', p)).toBe('wiring');
  });
  it('barrel without patch -> core', () => expect(cls('src/index.ts', null)).toBe('core'));
  it('barrel with a real statement -> core', () => {
    expect(cls('src/index.ts', patch("export * from './a.js';", 'const x = 1;'))).toBe('core');
  });
  it('barrel with no added lines -> core', () => {
    expect(cls('src/index.ts', '@@ -1 +0,0 @@\n-export * from "./a";')).toBe('core');
  });

  it('fallbacks to core', () => {
    expect(cls('src/config.ts', patch('x'))).toBe('core');
    expect(cls('./src/a.ts')).toBe('core');
  });
  it('first match wins', () => {
    expect(cls('docs/yarn.lock')).toBe('boilerplate');
    expect(cls('vendor/a.test.ts')).toBe('boilerplate');
  });
});

describe('sortGroup', () => {
  const f = (path: string, size: number, rank: number | null) => ({
    path,
    additions: size,
    deletions: 0,
    rank_percentile: rank,
  });
  it('rank desc, unranked last, then size desc, then path asc; does not mutate', () => {
    const input = [f('d', 1, null), f('c', 5, null), f('b', 1, 0.2), f('a', 1, 0.9), f('e', 5, 0.2)];
    expect(sortGroup(input).map((x) => x.path)).toEqual(['a', 'e', 'b', 'c', 'd']);
    expect(input[0]?.path).toBe('d');
  });
  it('path asc breaks full ties', () => {
    expect(sortGroup([f('b', 1, null), f('a', 1, null)]).map((x) => x.path)).toEqual(['a', 'b']);
  });
});

const fr = (over: Partial<FindingRef> & { id: string }): FindingRef => ({
  file: 'src/a.ts',
  start_line: 1,
  end_line: 1,
  severity: 'WARNING',
  dismissed_at: null,
  ...over,
});
const rev = (id: string, agent: string | null, at: string, findings: FindingRef[]): ReviewFindingsRead => ({
  id,
  agent_id: agent,
  created_at: at,
  findings,
});

describe('selectFindings', () => {
  const paths = new Set(['src/a.ts', 'src/b.ts']);
  it('keeps only the newest review per agent', () => {
    const out = selectFindings(
      [
        rev('r1', 'ag', '2026-01-01T00:00:00Z', [fr({ id: 'old' })]),
        rev('r2', 'ag', '2026-01-02T00:00:00Z', [fr({ id: 'new' })]),
      ],
      paths,
    );
    expect(out.map((x) => x.id)).toEqual(['new']);
  });
  it('null-agent reviews each count as their own agent', () => {
    const out = selectFindings(
      [
        rev('r1', null, '2026-01-01T00:00:00Z', [fr({ id: 'x' })]),
        rev('r2', null, '2026-01-02T00:00:00Z', [fr({ id: 'y' })]),
      ],
      paths,
    );
    expect(out.map((x) => x.id).sort()).toEqual(['x', 'y']);
  });
  it('drops dismissed findings and findings outside the PR; normalizes file', () => {
    const out = selectFindings(
      [
        rev('r', 'ag', '2026-01-01T00:00:00Z', [
          fr({ id: 'd', dismissed_at: '2026-01-01T00:00:00Z' }),
          fr({ id: 'o', file: 'src/other.ts' }),
          fr({ id: 'n', file: './src/b.ts' }),
        ]),
      ],
      paths,
    );
    expect(out.map((x) => x.id)).toEqual(['n']);
  });
});

describe('buildSmartDiff', () => {
  const file = (path: string, additions = 1, deletions = 0, p: string | null = null): ChangedFile => ({
    path,
    additions,
    deletions,
    patch: p,
  });
  const files = [
    file('pnpm-lock.yaml'),
    file('README.md'),
    file('package.json'),
    file('src/a.test.ts'),
    file('src/a.ts', 10, 0),
    file('src/b.ts', 3, 0),
  ];

  it('orders groups, omits empty ones, parses against the contract', () => {
    const out = buildSmartDiff(files, [], new Map());
    expect(out.groups.map((g) => g.role)).toEqual(['core', 'tests', 'wiring', 'docs', 'boilerplate']);
    expect(SmartDiff.safeParse(out).success).toBe(true);
    const small = buildSmartDiff([file('src/a.ts'), file('README.md')], [], new Map());
    expect(small.groups.map((g) => g.role)).toEqual(['core', 'docs']);
  });

  it('sorts a group by rank then size', () => {
    const out = buildSmartDiff(files, [], new Map([['src/b.ts', 0.9]]));
    const core = out.groups[0]!;
    expect(core.files.map((f) => f.path)).toEqual(['src/b.ts', 'src/a.ts']);
    expect(core.files[0]!.rank_percentile).toBe(0.9);
    expect(core.files[1]!.rank_percentile).toBeNull();
  });

  it('computes finding_ids / lines / max_severity / files_with_findings', () => {
    const out = buildSmartDiff(
      files,
      [
        fr({ id: 'w2', severity: 'WARNING', end_line: 20 }),
        fr({ id: 'c1', severity: 'CRITICAL', end_line: 50 }),
        fr({ id: 'w1', severity: 'WARNING', end_line: 5 }),
        fr({ id: 'x', file: 'README.md', severity: 'SUGGESTION', end_line: 2 }),
      ],
      new Map(),
    );
    const core = out.groups.find((g) => g.role === 'core')!;
    const a = core.files.find((f) => f.path === 'src/a.ts')!;
    expect(a.finding_ids).toEqual(['c1', 'w1', 'w2']);
    expect(a.finding_lines).toEqual([50, 5, 20]);
    expect(a.max_severity).toBe('CRITICAL');
    const b = core.files.find((f) => f.path === 'src/b.ts')!;
    expect(b.finding_ids).toEqual([]);
    expect(b.max_severity).toBeNull();
    expect(core.files_with_findings).toBe(1);
    const docs = out.groups.find((g) => g.role === 'docs')!;
    expect(docs.files_with_findings).toBe(1);
    expect(docs.files[0]!.max_severity).toBe('SUGGESTION');
    expect(out.groups.find((g) => g.role === 'tests')!.files_with_findings).toBe(0);
  });

  it('too_big only above 1000 lines; proposed_splits empty', () => {
    const at = buildSmartDiff([file('a.ts', 600, 400)], [], new Map());
    expect(at.split_suggestion).toEqual({ too_big: false, total_lines: 1000, proposed_splits: [] });
    const over = buildSmartDiff([file('a.ts', 601, 400)], [], new Map());
    expect(over.split_suggestion.too_big).toBe(true);
    expect(over.split_suggestion.total_lines).toBe(1001);
  });

  it('no files -> no groups', () => {
    expect(buildSmartDiff([], [], new Map()).groups).toEqual([]);
  });
});
